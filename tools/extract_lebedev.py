#!/usr/bin/env python3
"""Writes include/numsim-materials/core/lebedev_tables.h from uvwmaterial's sphere_lebedev_rule_bones.h.

usage: extract_lebedev.py <path to sphere_lebedev_rule_bones.h> [precisions...]

The tables (Lebedev & Laikov, BSD-3 in uvwmaterial) hold theta, phi in degrees and weights summing
to one; here they become unit vectors x = cos(theta) sin(phi), y = sin(theta) sin(phi), z = cos(phi).
"""
import math
import pathlib
import re
import sys

PRECISIONS = [3, 5, 7, 9, 11, 13, 15, 23]


def table(src: str, name: str) -> list[float]:
    body = re.search(rf"{name}\s*\[\s*\d*\s*\]\s*=?\s*\{{(.*?)\}}", src, re.S).group(1)
    return [float(x) for x in body.replace("\n", " ").split(",") if x.strip()]


def main() -> None:
    src = pathlib.Path(sys.argv[1]).read_text()
    precisions = [int(p) for p in sys.argv[2:]] or PRECISIONS
    out = ["// Generated by tools/extract_lebedev.py from uvwmaterial's Lebedev tables; do not edit.",
           "#ifndef NUMSIM_MATERIALS_CORE_LEBEDEV_TABLES_H", "#define NUMSIM_MATERIALS_CORE_LEBEDEV_TABLES_H", "",
           "#include <array>", "#include <cstddef>", "", "namespace numsim::materials::lebedev::detail {", "",
           "struct node { double x, y, z, w; };", ""]
    for p in precisions:
        theta, phi, w = (table(src, f"_{n}_{p}") for n in ("theta", "phi", "weight"))
        assert len(theta) == len(phi) == len(w)
        out.append(f"inline constexpr std::array<node, {len(w)}> precision_{p}{{{{")
        for t, f, wi in zip(theta, phi, w):
            t, f = math.radians(t), math.radians(f)
            out.append(f"    {{{math.cos(t) * math.sin(f):.17g}, {math.sin(t) * math.sin(f):.17g}, {math.cos(f):.17g}, {wi:.17g}}},")
        out.append("}};")
        out.append("")
    out += ["} // namespace numsim::materials::lebedev::detail", "", "#endif // NUMSIM_MATERIALS_CORE_LEBEDEV_TABLES_H", ""]
    pathlib.Path(__file__).resolve().parent.parent.joinpath("include/numsim-materials/core/lebedev_tables.h").write_text("\n".join(out))
    print("precisions", precisions, "points", [len(table(src, f"_weight_{p}")) for p in precisions])


if __name__ == "__main__":
    main()
